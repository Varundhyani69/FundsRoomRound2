    PRIMARY KEY (id),
    KEY ix_customer_orders_item_location (item_id, location_id),
    KEY ix_customer_orders_status (status),
    KEY ix_customer_orders_created_by (created_by),
    CONSTRAINT fk_customer_orders_item FOREIGN KEY (item_id)
        REFERENCES items (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_customer_orders_location FOREIGN KEY (location_id)
        REFERENCES locations (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_customer_orders_created_by FOREIGN KEY (created_by)
        REFERENCES users (id) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT ck_customer_orders_quantity CHECK (quantity BETWEEN 1 AND 1000000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

-- Which batches an order actually drew its reservation from.
--
-- Under MongoDB these lines were an embedded array on the order document. In a
-- relational schema they become a child table: one row per batch drawn from, which
-- is what lets the reservation lines be queried and aggregated on their own (for
-- example "how much of batch X is spoken for, and by whom") instead of only ever
-- being read back as part of their parent order.
--
-- CASCADE here, unlike everywhere else in this schema: a reservation line has no
-- meaning without its order, so deleting the order must take its lines with it
-- rather than leaving orphans behind.
CREATE TABLE IF NOT EXISTS customer_order_reservations (
    id                CHAR(24)     NOT NULL,
    customer_order_id CHAR(24)     NOT NULL,
    item_id           CHAR(24)     NOT NULL,
    location_id       CHAR(24)     NOT NULL,
    batch             VARCHAR(32)  NOT NULL,
    quantity          INT UNSIGNED NOT NULL,
    created_at        DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    -- One line per batch per order: an order draws from any given batch once, in a
    -- single ascending-batch pass (Req 15.6).
    UNIQUE KEY uq_reservation_order_batch (customer_order_id, item_id, location_id, batch),
    KEY ix_reservation_item_location_batch (item_id, location_id, batch),
    CONSTRAINT fk_reservation_order FOREIGN KEY (customer_order_id)
        REFERENCES customer_orders (id) ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_reservation_item FOREIGN KEY (item_id)
        REFERENCES items (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_reservation_location FOREIGN KEY (location_id)
        REFERENCES locations (id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_reservation_quantity CHECK (quantity BETWEEN 1 AND 1000000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;
